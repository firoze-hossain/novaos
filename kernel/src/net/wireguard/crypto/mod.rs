//! kernel/src/net/wireguard/crypto/mod.rs
//!
//! NovaOS 2.0 (Month 3 - Server & Containers): Native In-Kernel WireGuard VPN
//!
//! Cryptographic primitives: Curve25519 / X25519, ChaCha20-Poly1305 AEAD,
//! BLAKE2s-256, HMAC-BLAKE2s, and TAI64N.

pub mod x25519;
pub mod chacha20poly1305;
pub mod blake2s;
pub mod tai64n;

pub use x25519::{x25519, public_key};
pub use chacha20poly1305::{chacha20poly1305_encrypt, chacha20poly1305_decrypt};
pub use blake2s::{blake2s_256, blake2s_mac16, kdf1, kdf2, kdf3};
pub use tai64n::Tai64n;

/// Self-test all cryptographic primitives against official RFC test vectors.
pub fn run_crypto_selftest() -> bool {
    // 1. Test X25519 (RFC 7748 Section 6.1)
    let alice_priv: [u8; 32] = [
        0x77, 0x07, 0x6d, 0x0a, 0x73, 0x18, 0xa5, 0x7d,
        0x3c, 0x16, 0xc1, 0x72, 0x51, 0xb2, 0x66, 0x45,
        0xdf, 0x4c, 0x2f, 0x87, 0xeb, 0xc0, 0x99, 0x2a,
        0xb1, 0x77, 0xfb, 0xa5, 0x1d, 0xb9, 0x2c, 0x2a,
    ];
    let alice_pub_expected: [u8; 32] = [
        0x85, 0x20, 0xf0, 0x09, 0x89, 0x30, 0xa7, 0x54,
        0x74, 0x8b, 0x7d, 0xdc, 0xb4, 0x3e, 0xf7, 0x5a,
        0x0d, 0xbf, 0x3a, 0x0d, 0x26, 0x38, 0x1a, 0xf4,
        0xeb, 0xa4, 0xa9, 0x8e, 0xaa, 0x9b, 0x4e, 0x6a,
    ];
    let alice_pub = public_key(&alice_priv);
    if alice_pub != alice_pub_expected {
        return false;
    }

    let bob_priv: [u8; 32] = [
        0x5d, 0xab, 0x08, 0x7e, 0x62, 0x4a, 0x8a, 0x4b,
        0x79, 0xe1, 0x7f, 0x8b, 0x83, 0x80, 0x0e, 0xe6,
        0x6f, 0x3b, 0xb1, 0x29, 0x26, 0x18, 0xb6, 0xfd,
        0x1c, 0x2f, 0x8b, 0x27, 0xff, 0x88, 0xe0, 0xeb,
    ];
    let bob_pub_expected: [u8; 32] = [
        0xde, 0x9e, 0xdb, 0x7d, 0x7b, 0x7d, 0xc1, 0xb4,
        0xd3, 0x5b, 0x61, 0xc2, 0xec, 0xe4, 0x35, 0x37,
        0x3f, 0x83, 0x43, 0xc8, 0x5b, 0x78, 0x67, 0x4d,
        0xad, 0xfc, 0x7e, 0x14, 0x6f, 0x88, 0x2b, 0x4f,
    ];
    let bob_pub = public_key(&bob_priv);
    if bob_pub != bob_pub_expected {
        return false;
    }

    let shared_expected: [u8; 32] = [
        0x4a, 0x5d, 0x9d, 0x5b, 0xa4, 0xce, 0x2d, 0xe1,
        0x72, 0x8e, 0x3b, 0xf4, 0x80, 0x35, 0x0f, 0x25,
        0xe0, 0x7e, 0x21, 0xc9, 0x47, 0xd1, 0x9e, 0x33,
        0x76, 0xf0, 0x9b, 0x3c, 0x1e, 0x16, 0x17, 0x42,
    ];
    let shared_alice = x25519(&alice_priv, &bob_pub);
    let shared_bob = x25519(&bob_priv, &alice_pub);
    if shared_alice != shared_expected || shared_bob != shared_expected {
        return false;
    }

    // 2. Test ChaCha20-Poly1305 AEAD (RFC 7539 Section 2.8.2)
    let mut key = [0u8; 32];
    for i in 0..32 {
        key[i] = 0x80 + i as u8;
    }
    let nonce = [0x07, 0x00, 0x00, 0x00, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47];
    let aad = [0x50, 0x51, 0x52, 0x53, 0xc0, 0xc1, 0xc2, 0xc3, 0xc4, 0xc5, 0xc6, 0xc7];
    let plaintext = b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.";

    let mut ct_and_tag = [0u8; 114 + 16];
    chacha20poly1305_encrypt(&key, &nonce, &aad, plaintext, &mut ct_and_tag);

    let expected_tag = [
        0x1a, 0xe1, 0x0b, 0x59, 0x4f, 0x09, 0xe2, 0x6a,
        0x7e, 0x90, 0x2e, 0xcb, 0xd0, 0x60, 0x06, 0x91,
    ];
    if &ct_and_tag[114..] != &expected_tag {
        return false;
    }

    let mut decrypted = [0u8; 114];
    match chacha20poly1305_decrypt(&key, &nonce, &aad, &ct_and_tag, &mut decrypted) {
        Ok(len) => {
            if len != 114 || &decrypted[..] != plaintext {
                return false;
            }
        }
        Err(_) => return false,
    }

    // 3. Test BLAKE2s-256 (RFC 7693)
    let digest = blake2s_256(b"abc");
    let expected_digest = [
        0x50, 0x8c, 0x5e, 0x8c, 0x32, 0x7c, 0x14, 0xe2,
        0xe1, 0xa7, 0x2b, 0xa3, 0x4e, 0xeb, 0x45, 0x2f,
        0x37, 0x45, 0x8b, 0x20, 0x9e, 0xd6, 0x3a, 0x29,
        0x4d, 0x99, 0x9b, 0x4c, 0x86, 0x67, 0x59, 0x82,
    ];
    if digest != expected_digest {
        return false;
    }

    // 4. Test WireGuard Initial Constants
    let proto = b"Noise_IKpsk2_25519_ChaChaPoly_BLAKE2s";
    let ck0 = blake2s_256(proto);
    let expected_ck0 = [
        0x60, 0xe2, 0x6d, 0xae, 0xf3, 0x27, 0xef, 0xc0,
        0x2e, 0xc3, 0x35, 0xe2, 0xa0, 0x25, 0xd2, 0xd0,
        0x16, 0xeb, 0x42, 0x06, 0xf8, 0x72, 0x77, 0xf5,
        0x2d, 0x38, 0xd1, 0x98, 0x8b, 0x78, 0xcd, 0x36,
    ];
    if ck0 != expected_ck0 {
        return false;
    }

    let mut h0_buf = [0u8; 32 + 34];
    h0_buf[..32].copy_from_slice(&ck0);
    h0_buf[32..].copy_from_slice(b"WireGuard v1 zx2c4 Jason@zx2c4.com");
    let h0 = blake2s_256(&h0_buf);
    let expected_h0 = [
        0x22, 0x11, 0xb3, 0x61, 0x08, 0x1a, 0xc5, 0x66,
        0x69, 0x12, 0x43, 0xdb, 0x45, 0x8a, 0xd5, 0x32,
        0x2d, 0x9c, 0x6c, 0x66, 0x22, 0x93, 0xe8, 0xb7,
        0x0e, 0xe1, 0x9c, 0x65, 0xba, 0x07, 0x9e, 0xf3,
    ];
    if h0 != expected_h0 {
        return false;
    }

    // 5. Test TAI64N ordering
    let t1 = Tai64n::new(1000, 50);
    let t2 = Tai64n::new(1000, 100);
    let t3 = Tai64n::new(1001, 10);
    if !t2.is_after(&t1) || !t3.is_after(&t2) || t1.is_after(&t2) {
        return false;
    }

    true
}
