#ifndef GUI_FONT5X7_H
#define GUI_FONT5X7_H

#include "../include/types.h"

/* Digits only (0-9), 5 columns x 7 rows, one byte per row using bits
 * 4..0 (bit4 = leftmost column). Deliberately small and hand-built
 * rather than a full ASCII bitmap font transcribed from memory - see
 * PROGRESS.md for why: this phase's windowing demo only ever needs to
 * label windows "1"/"2"/"3", so a full font would be a lot of extra
 * risk (getting dozens of glyphs exactly right) for no benefit here. */
static const uint8_t font5x7_digits[10][7] = {
    { 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E }, /* 0 */
    { 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E }, /* 1 */
    { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F }, /* 2 */
    { 0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E }, /* 3 */
    { 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02 }, /* 4 */
    { 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E }, /* 5 */
    { 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E }, /* 6 */
    { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08 }, /* 7 */
    { 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E }, /* 8 */
    { 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C }, /* 9 */
};

#endif
