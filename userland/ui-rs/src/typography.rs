//! Typography Scale, Metrics, and Embedded Glyph System for NovaOS
//!
//! Provides a structured type scale, text alignment, string dimension
//! measurement, and a complete embedded 5x7 printable ASCII font (32..=126).

use crate::geom::Size;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum TypeScale {
    Caption,   // Smallest labels, status bars, timestamps (1x scale, compact)
    Body,      // Standard application text, buttons, inputs (1x scale, normal spacing)
    BodyBold,  // Emphasized list titles, active tabs (1x scale, boldened)
    Subtitle,  // Group headers, card titles (1.5x / scaled)
    Title,     // Window titlebars, dialog headers (2x scale)
    Heading,   // Section titles, wizard headers (2x scale)
    Display,   // Hero text, lockscreen clock (3x / 4x scale)
}

impl TypeScale {
    /// Font pixel multiplier (1 for 1x, 2 for 2x, etc.)
    pub const fn pixel_scale(&self) -> i32 {
        match self {
            TypeScale::Caption => 1,
            TypeScale::Body => 1,
            TypeScale::BodyBold => 1,
            TypeScale::Subtitle => 2,
            TypeScale::Title => 2,
            TypeScale::Heading => 2,
            TypeScale::Display => 3,
        }
    }

    pub const fn line_height(&self) -> i32 {
        match self {
            TypeScale::Caption => 9,
            TypeScale::Body => 12,
            TypeScale::BodyBold => 12,
            TypeScale::Subtitle => 16,
            TypeScale::Title => 18,
            TypeScale::Heading => 20,
            TypeScale::Display => 28,
        }
    }

    pub const fn letter_spacing(&self) -> i32 {
        match self {
            TypeScale::Caption => 1,
            TypeScale::Body => 1,
            TypeScale::BodyBold => 2,
            TypeScale::Subtitle => 2,
            TypeScale::Title => 2,
            TypeScale::Heading => 2,
            TypeScale::Display => 3,
        }
    }
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum TextAlign {
    Left,
    Center,
    Right,
}

