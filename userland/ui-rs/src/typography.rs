/// Returns the 7 row masks for an ASCII byte in the printable range (32..=126).
/// Non-printable characters fallback to space or a hollow box.
pub fn get_glyph(c: u8) -> &'static [u8; 7] {
    if c >= 32 && c <= 126 {
        &FONT_5X7[(c - 32) as usize]
    } else {
        &FONT_5X7[0] // fallback to space
    }
}

/// Measures text width and height given a type scale.
pub fn measure_text(text: &str, scale: TypeScale) -> Size {
    let px = scale.pixel_scale();
    let l_spacing = scale.letter_spacing();
    let char_w = GLYPH_WIDTH * px;
    let mut max_w = 0;
    let mut current_w = 0;
    let mut lines = 1;

    for b in text.bytes() {
        if b == b'\n' {
            if current_w > max_w {
                max_w = current_w;
            }
            current_w = 0;
            lines += 1;
        } else {
            current_w += char_w + l_spacing;
        }
    }
    if current_w > max_w {
        max_w = current_w;
    }

    let h = lines * scale.line_height();
    Size::new(max_w, h)
}
