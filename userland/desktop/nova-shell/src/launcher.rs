//! userland/desktop/nova-shell/src/launcher.rs
//!
//! NovaOS Application Launcher & Spotlight Search.
//! Synthesizes macOS Launchpad / Spotlight and Windows 11 Start Menu into a unified application grid.
//! Integrates directly with `nova-bundle` to discover `.app` bundles, handle drag-and-drop installation,
//! inspect declared sandbox permissions, and launch applications with isolated capabilities.

