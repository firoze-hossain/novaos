#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::YamlParser;

    #[test]
    fn test_parse_netplan_dhcp() {
        let yaml_text = r#"
version: 2
ethernets:
  eth0:
    dhcp4: true
    dhcp6: false
    mtu: 1500
"#;
        let val = YamlParser::parse(yaml_text).unwrap();
        let net = ParsedNetworkConfig::parse_netplan_v2(&val).unwrap();

        let eth0 = net.interfaces.get("eth0").expect("eth0 interface");
        assert!(eth0.dhcp4);
        assert!(!eth0.dhcp6);
        assert_eq!(eth0.mtu, Some(1500));

        let ifaces_file = net.generate_interfaces_file();
        assert!(ifaces_file.contains("auto eth0"));
        assert!(ifaces_file.contains("iface eth0 inet dhcp"));
        assert!(ifaces_file.contains("mtu 1500"));
    }

    #[test]
    fn test_parse_netplan_static_ip_and_dns() {
        let yaml_text = r#"
version: 2
ethernets:
  enp0s3:
    dhcp4: false
    addresses:
      - 10.0.10.50/24
    gateway4: 10.0.10.1
    nameservers:
      addresses: [1.1.1.1, 8.8.8.8]
      search: [enterprise.novaos.internal]
"#;
        let val = YamlParser::parse(yaml_text).unwrap();
        let net = ParsedNetworkConfig::parse_netplan_v2(&val).unwrap();

        let iface = net.interfaces.get("enp0s3").expect("enp0s3");
        assert_eq!(iface.addresses, vec!["10.0.10.50/24"]);
        assert_eq!(iface.gateway4, Some("10.0.10.1".into()));
        assert_eq!(iface.nameservers.len(), 2);

        let ifaces_file = net.generate_interfaces_file();
        assert!(ifaces_file.contains("auto enp0s3"));
        assert!(ifaces_file.contains("iface enp0s3 inet static"));
        assert!(ifaces_file.contains("address 10.0.10.50"));
        assert!(ifaces_file.contains("netmask 255.255.255.0"));
        assert!(ifaces_file.contains("gateway 10.0.10.1"));

        let resolv = net.generate_resolv_conf();
        assert!(resolv.contains("search enterprise.novaos.internal"));
        assert!(resolv.contains("nameserver 1.1.1.1"));
        assert!(resolv.contains("nameserver 8.8.8.8"));
    }
}
