//! userland/server/novainit/src/network.rs
//!
//! Cloud-Init Network Configuration Engine (Netplan v2 & Debian Interfaces v1 format).

use std::collections::BTreeMap;
use crate::parser::YamlValue;

#[derive(Debug, Clone, Default, PartialEq)]
pub struct EthernetInterface {
    pub name: String,
    pub dhcp4: bool,
    pub dhcp6: bool,
    pub addresses: Vec<String>,
    pub gateway4: Option<String>,
    pub nameservers: Vec<String>,
    pub search_domains: Vec<String>,
    pub mtu: Option<u32>,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct ParsedNetworkConfig {
    pub version: u32,
    pub interfaces: BTreeMap<String, EthernetInterface>,
}

impl ParsedNetworkConfig {
    /// Parses network configuration from YAML (Netplan Version 2 format)
    pub fn parse_netplan_v2(yaml: &YamlValue) -> Result<Self, String> {
        let mut config = ParsedNetworkConfig {
            version: yaml.get_int("version").unwrap_or(2) as u32,
            interfaces: BTreeMap::new(),
        };

        // If top-level contains 'network', unwrap it
        let root = if let Some(net) = yaml.get("network") {
            net
        } else {
            yaml
        };

        if let Some(ethernets) = root.get("ethernets").and_then(|e| e.as_map()) {
            for (if_name, if_val) in ethernets {
                let mut eth = EthernetInterface {
                    name: if_name.clone(),
                    dhcp4: if_val.get_bool("dhcp4").unwrap_or(false),
                    dhcp6: if_val.get_bool("dhcp6").unwrap_or(false),
                    addresses: Vec::new(),
                    gateway4: if_val.get_str("gateway4").map(|s| s.to_string()),
                    nameservers: Vec::new(),
                    search_domains: Vec::new(),
                    mtu: if_val.get_int("mtu").map(|i| i as u32),
                };

                // Static IP addresses
                if let Some(addrs) = if_val.get("addresses").and_then(|a| a.as_list()) {
                    for addr in addrs {
                        if let Some(s) = addr.as_str() {
                            eth.addresses.push(s.to_string());
                        }
                    }
                }

                // Gateway in routes if not in gateway4
                if eth.gateway4.is_none() {
                    if let Some(routes) = if_val.get("routes").and_then(|r| r.as_list()) {
                        for route in routes {
                            if route.get_str("to") == Some("default") || route.get_str("to") == Some("0.0.0.0/0") {
                                if let Some(via) = route.get_str("via") {
                                    eth.gateway4 = Some(via.to_string());
                                }
                            }
                        }
                    }
                }

                // Nameservers
                if let Some(ns) = if_val.get("nameservers") {
                    if let Some(ns_addrs) = ns.get("addresses").and_then(|a| a.as_list()) {
                        for addr in ns_addrs {
                            if let Some(s) = addr.as_str() {
                                eth.nameservers.push(s.to_string());
                            }
                        }
                    }
                    if let Some(search) = ns.get("search").and_then(|s| s.as_list()) {
                        for s in search {
                            if let Some(sd) = s.as_str() {
                                eth.search_domains.push(sd.to_string());
                            }
                        }
                    }
                }

                config.interfaces.insert(if_name.clone(), eth);
            }
        }

        Ok(config)
    }

    /// Generates `/etc/network/interfaces` configuration text
    pub fn generate_interfaces_file(&self) -> String {
        let mut out = String::new();
        out.push_str("# Generated by NovaOS novainit (cloud-init)\n\n");
        out.push_str("auto lo\niface lo inet loopback\n\n");

        for (name, iface) in &self.interfaces {
            out.push_str(&format!("auto {}\n", name));
            if iface.dhcp4 {
                out.push_str(&format!("iface {} inet dhcp\n", name));
            } else if !iface.addresses.is_empty() {
                out.push_str(&format!("iface {} inet static\n", name));
                // Split CIDR e.g. 192.168.1.100/24 into address and netmask
                let cidr = &iface.addresses[0];
                if let Some(pos) = cidr.find('/') {
                    let ip = &cidr[..pos];
                    let prefix = cidr[pos + 1..].parse::<u32>().unwrap_or(24);
                    let mask = cidr_to_netmask(prefix);
                    out.push_str(&format!("    address {}\n", ip));
                    out.push_str(&format!("    netmask {}\n", mask));
                } else {
                    out.push_str(&format!("    address {}\n", cidr));
                    out.push_str("    netmask 255.255.255.0\n");
                }
                if let Some(ref gw) = iface.gateway4 {
                    out.push_str(&format!("    gateway {}\n", gw));
                }
            } else {
                out.push_str(&format!("iface {} inet manual\n", name));
            }
            if let Some(mtu) = iface.mtu {
                out.push_str(&format!("    mtu {}\n", mtu));
            }
            out.push('\n');
        }
        out
    }

    /// Generates `/etc/resolv.conf` text
    pub fn generate_resolv_conf(&self) -> String {
        let mut out = String::new();
        out.push_str("# Generated by NovaOS novainit (cloud-init)\n");

        let mut all_search = Vec::new();
        let mut all_ns = Vec::new();

        for iface in self.interfaces.values() {
            for s in &iface.search_domains {
                if !all_search.contains(s) {
                    all_search.push(s.clone());
                }
            }
            for ns in &iface.nameservers {
                if !all_ns.contains(ns) {
                    all_ns.push(ns.clone());
                }
            }
        }

        if !all_search.is_empty() {
            out.push_str(&format!("search {}\n", all_search.join(" ")));
        }

        if all_ns.is_empty() {
            // Default fallback nameservers
            out.push_str("nameserver 1.1.1.1\nnameserver 8.8.8.8\n");
        } else {
            for ns in all_ns {
                out.push_str(&format!("nameserver {}\n", ns));
            }
        }
        out
    }
}

/// Converts CIDR prefix length (e.g. 24) to dotted decimal netmask (e.g. 255.255.255.0)
pub fn cidr_to_netmask(prefix: u32) -> String {
    let mask_u32: u32 = if prefix == 0 {
        0
    } else {
        !0u32 << (32 - prefix.min(32))
    };
    format!(
        "{}.{}.{}.{}",
        (mask_u32 >> 24) & 0xFF,
        (mask_u32 >> 16) & 0xFF,
        (mask_u32 >> 8) & 0xFF,
        mask_u32 & 0xFF
    )
}

// -----------------------------------------------------------------------------
// Unit Tests
