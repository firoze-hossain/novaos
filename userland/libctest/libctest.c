/*
 * libctest.c - the in-OS half of the libc test (Phase 73). The other half,
 * userland/libc/tests/, runs the same library code against a FAKE kernel
 * on the host and can hammer it hundreds of thousands of times; this
 * program proves the same code works against the GENUINE kernel: real
 * int 0x80 syscalls, a real FAT32 and ext2 filesystem, a real ELF load,
 * real processes. kernel/task/exec_trust_demo.c runs it via
 * SYS_EXEC_TRUSTED (so it holds can_open_any_file and can_spawn - the
 * same trust TPROBE.ELF needs to write files) and checks its exit code;
 * tools/python/test_runner.py checks the "[libctest] PASS: ..." lines.
 *
 * Every failure prints "[libctest] FAIL: ..." - the uppercase word is
 * deliberate: it also trips test_runner.py's global no-FAIL assertion, so
 * a regression here can never slip through unnoticed.
 *
 * The same binary is also its own child process: "--envchild",
 * "--envempty" and "--envbig" make it check the environment the parent
 * passed and exit 0/non-zero, which is how environment inheritance is
 * tested across a real exec.
 */
#include <errno.h>
#include <novasys.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int failed_groups;
static const char* first_fail_expr;
static int first_fail_line;

/* Records only the FIRST failed check of a group, so the report names
 * exactly what broke instead of a cascade. */
#define CHECK(c) do { if (!(c) && first_fail_expr == NULL) { \
    first_fail_expr = #c; first_fail_line = __LINE__; } } while (0)

static void group_begin(void) {
    first_fail_expr = NULL;
    first_fail_line = 0;
}

static void group_end(const char* name) {
    if (first_fail_expr == NULL) {
        printf("[libctest] PASS: %s\n", name);
    } else {
        failed_groups++;
        printf("[libctest] FAIL: %s (line %d: %s; errno=%d %s)\n", name,
               first_fail_line, first_fail_expr, errno, strerror(errno));
    }
}

/* Deterministic content, shared with tools/fixtures/ext2root/EXT2BIG.BIN
 * (generated by the same formula). */
static unsigned char pat(unsigned int i) {
    return (unsigned char)(i * 7u + (i >> 8) + 3u);
}

static int pattern_ok(const unsigned char* p, unsigned int n,
                      unsigned int base) {
    for (unsigned int i = 0; i < n; i++) {
        if (p[i] != pat(base + i)) {
            return 0;
        }
    }
    return 1;
}

/* Reads a file end to end through the raw syscalls in pieces of `piece`
 * bytes - odd sizes make the kernel start reads part-way into a FAT32
 * cluster / ext2 block, which whole-file fopen() (4 KiB-aligned reads)
 * never does. Returns the number of bytes read, or -1 on any mismatch. */
static int raw_read_all(const char* name, unsigned int piece,
                        unsigned int expect_len) {
    int h = sys_open(name);
    if (h < 0) {
        return -1;
    }
    unsigned char buf[512];
    unsigned int total = 0;
    for (;;) {
        int n = sys_read(h, buf, (int)piece);
        if (n < 0) {
            sys_close(h);
            return -1;
        }
        if (n == 0) {
            break;
        }
        if (!pattern_ok(buf, (unsigned int)n, total)) {
            sys_close(h);
            return -1;
        }
        total += (unsigned int)n;
    }
    sys_close(h);
    return total == expect_len ? (int)total : -1;
}

