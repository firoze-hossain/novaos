static int spawn_wait(const char* mode, int trusted_env_explicit,
                      char** explicit_env) {
    char* av[3] = { (char*)"LIBCTEST.ELF", (char*)mode, NULL };
    int pid = trusted_env_explicit
                  ? sys_exec_trusted_env("LIBCTEST.ELF", av, 2, explicit_env)
                  : sys_exec_trusted("LIBCTEST.ELF", av, 2);
    if (pid < 0) {
        return -1000;
    }
    return sys_wait(pid);
}

static void test_env_inheritance(void) {
    group_begin();
    clearenv();
    CHECK(setenv("NOVA_ENV_TEST", "from-parent", 1) == 0);
    CHECK(setenv("NOVA_ENV_TEST2", "two words", 1) == 0);

    /* default: the libc sys_exec_trusted() wrapper hands over environ */
    CHECK(spawn_wait("--envchild", 0, NULL) == 0);

    /* an explicit NULL environment overrides it: the child sees none */
    CHECK(spawn_wait("--envempty", 1, NULL) == 0);

    /* an environment exactly at the 4096-byte limit is accepted and
     * arrives intact: "N=" + 4093 characters + NUL == 4096 */
    static char bigenv[4096];
    bigenv[0] = 'N'; bigenv[1] = '=';
    for (int i = 2; i < 4095; i++) bigenv[i] = 'x';
    bigenv[4095] = '\0';
    char* big_env[2] = { bigenv, NULL };
    CHECK(spawn_wait("--envbig", 1, big_env) == 0);
    group_end("environment inherited by a child process");
}

static void test_env_limits(void) {
    group_begin();
    char* av[2] = { (char*)"LIBCTEST.ELF", NULL };

    /* 33 variables: one over the limit. The kernel must refuse (-1)
     * rather than truncate silently - bypassing libc's own setenv()
     * limit by building the array by hand. */
    char* many[34];
    for (int i = 0; i < 33; i++) many[i] = (char*)"A=1";
    many[33] = NULL;
    CHECK(sys_exec_trusted_env("LIBCTEST.ELF", av, 1, many) == -1);

    /* one byte over 4096 */
    static char over[4098];
    over[0] = 'H'; over[1] = '=';
    for (int i = 2; i < 4096; i++) over[i] = 'h';
    over[4096] = '\0';                       /* strlen 4096 + NUL = 4097 */
    char* over_env[2] = { over, NULL };
    CHECK(sys_exec_trusted_env("LIBCTEST.ELF", av, 1, over_env) == -1);

    /* libc itself refuses to build such an environment, so it can
     * never hand its own children one the kernel would reject */
    clearenv();
    errno = 0;
    CHECK(setenv("BIG", over, 1) == -1 && errno == ENOMEM);
    group_end("kernel enforces the environment size limits");
}

static void test_printf(void) {
    group_begin();
    char buf[64];
    int n = snprintf(buf, sizeof buf, "%5d|%-5s|%04x|%c|%%|%s|%u", 42, "ab",
                     0xbeef, 'z', "end", 4000000000u);
    CHECK(n == 35 && strcmp(buf, "   42|ab   |beef|z|%|end|4000000000") == 0);
    CHECK(snprintf(buf, 4, "%s", "abcdef") == 6 && strcmp(buf, "abc") == 0);
    CHECK(snprintf(NULL, 0, "%s", "hello") == 5);
    CHECK(snprintf(buf, sizeof buf, "%d", -2147483647 - 1) == 11 &&
          strcmp(buf, "-2147483648") == 0);

    /* printf returns the length and, unlike the old fixed-512-byte
     * version, never truncates */
    int len = printf("[libctest] printf length probe %d\n", 12345);
    CHECK(len == 37);
    static char longs[700];
    for (int i = 0; i < 699; i++) longs[i] = (char)('a' + i % 26);
    longs[699] = '\0';
    CHECK(fprintf(stdout, "%s\n", longs) == 700);
    group_end("printf/snprintf formatting");
}

