static int child_main(const char* mode) {
    if (strcmp(mode, "--envchild") == 0) {
        const char* a = getenv("NOVA_ENV_TEST");
        const char* b = getenv("NOVA_ENV_TEST2");
        int n = 0;
        while (environ != NULL && environ[n] != NULL) n++;
        int ok = a != NULL && strcmp(a, "from-parent") == 0 &&
                 b != NULL && strcmp(b, "two words") == 0 && n == 2;
        /* and the child can extend what it inherited */
        ok = ok && setenv("NOVA_CHILD", "yes", 1) == 0 && getenv("NOVA_CHILD") != NULL;
        printf("[libctest-child] envchild %s (vars=%d)\n", ok ? "ok" : "MISMATCH", n);
        return ok ? 0 : 10;
    }
    if (strcmp(mode, "--envempty") == 0) {
        int ok = getenv("NOVA_ENV_TEST") == NULL &&
                 (environ == NULL || environ[0] == NULL);
        printf("[libctest-child] envempty %s\n", ok ? "ok" : "MISMATCH");
        return ok ? 0 : 11;
    }
    if (strcmp(mode, "--envbig") == 0) {
        const char* v = getenv("N");
        int ok = v != NULL && strlen(v) == 4093;
        for (int i = 0; ok && i < 4093; i++) if (v[i] != 'x') ok = 0;
        printf("[libctest-child] envbig %s\n", ok ? "ok" : "MISMATCH");
        return ok ? 0 : 12;
    }
    return 13;
}

int main(int argc, char** argv, char** envp) {
    (void)envp;
    if (argc >= 2) {
        return child_main(argv[1]);
    }

    test_allocator();
    test_errno();
    test_file_roundtrip();
    test_large_fat32_file();
    test_ext2();
    test_environment();
    test_env_inheritance();
    test_env_limits();
    test_printf();

    printf("[libctest] DONE: 9 groups, %d failed\n", failed_groups);
    return failed_groups;
}
